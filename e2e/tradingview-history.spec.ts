import { expect, test } from '@playwright/test'
import { registerAccount } from './account-helper'

test('previews, cancels, imports once and corrects missing private trade details', async ({ page, request, browser }) => {
  test.setTimeout(90_000)
  await registerAccount(page, request, 'tradehistory')
  const upload = async () => {
    await page.getByLabel('TradingView history CSV').setInputFiles('lib/trades/fixtures/tradingview-history.csv')
    await page.getByLabel('Export timezone').fill('UTC')
    await page.getByRole('button', { name: 'Preview trades', exact: true }).click()
    await expect(page.getByText('6 closed trades ready to import.')).toBeVisible()
    await expect(page.getByRole('button', { name: 'Continue', exact: true })).toBeDisabled()
    await page.getByLabel('I confirm this is the timezone used by the export').check()
  }
  await upload()
  await expect(page.locator('.history-import [role=alert]')).toContainText('R-based charts and totals, and setup analysis will be incomplete')
  await page.screenshot({ path: '/tmp/oneliner-history-preview.png', fullPage: true })
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  expect((await (await page.request.get('/api/trades')).json()).trades).toHaveLength(0)
  await upload()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByText('Saved 6 trades. 0 already present.')).toBeVisible()
  const saved = (await (await page.request.get('/api/trades?week=2026-03-16')).json())
  expect(saved.trades).toHaveLength(6)
  expect(saved.summary).toMatchObject({ completedCount: 6, wins: 3, winRate: 0.5, totalR: null, missingRCount: 6 })
  expect((await (await page.request.get('/api/trades?status=open')).json()).trades).toHaveLength(0)
  await upload()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByText('Saved 0 trades. 6 already present.')).toBeVisible()
  const imported = page.getByRole('region', { name: 'Imported trades', exact: true })
  await expect(imported.getByText('Edit details', { exact: true })).toHaveCount(6)
  const card = imported.locator('article').first()
  await expect(card.getByText('Missing note · Missing initial stop · Missing setup')).toBeVisible()
  await card.getByText('Edit details').click()
  const side = await card.getByLabel('Direction').inputValue()
  await card.getByLabel('Initial stop').fill(side === 'long' ? '99.25' : '101.25')
  await card.getByLabel('Setup name').fill('Opening range')
  await card.getByLabel('I reviewed these corrections').check()
  await card.getByRole('button', { name: 'Save corrections' }).click()
  await expect(imported.getByText('Missing note · Missing initial stop · Missing setup')).toHaveCount(5)
  const after = (await (await page.request.get('/api/trades?week=2026-03-16')).json())
  expect(after.summary.missingRCount).toBe(5)
  const edited = after.trades.find((trade: { setup: string | null }) => trade.setup === 'Opening range')
  expect(edited.r_result).not.toBeNull()
  expect(edited.original_note).toBeNull()
  expect(edited.source_net_pnl_usd).toBe(saved.trades.find((trade: { id: string }) => trade.id === edited.id).source_net_pnl_usd)
  const context = await browser.newContext()
  try {
    const other = await context.newPage()
    await registerAccount(other, request, 'tradehistoryother')
    expect((await (await other.request.get('/api/trades')).json()).trades).toHaveLength(0)
    expect((await other.request.patch(`/api/trades/${edited.id}`, { data: { exitPrice: '500' } })).status()).toBe(404)
  } finally { await context.close() }
})
