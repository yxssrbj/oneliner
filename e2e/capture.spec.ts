test('local sign-out clears a draft away from capture when remote logout fails', async ({ page, request }) => {
  await registerAccount(page, request, 'capture-logout-failure')
  await page.getByLabel('Trade note').fill('private draft before failed remote logout')
  await page.goto('/settings')
  await page.route('**/auth/v1/logout*', route => route.fulfill({ status: 503, json: { message: 'Unavailable' } }))
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.locator('.settings-sign-out [role=alert]')).toHaveText('Could not sign out. Try again.')
  expect(await page.evaluate(() => Object.keys(sessionStorage).filter(key => key.startsWith('oneliner:capture:')))).toEqual([])
  await page.unroute('**/auth/v1/logout*')
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page).toHaveURL(/\/sign-in$/)
  expect((await page.request.get('/api/trades?recent=3')).status()).toBe(401)
})
