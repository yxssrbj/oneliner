import { expect, test } from '@playwright/test'
import { registerAccount } from './account-helper'

const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4//8/AwAI/AL+XBGVAAAAAElFTkSuQmCC','base64')

test('two members exchange text and pictures; removal revokes history and bytes', async ({ page, request, browser }) => {
  test.setTimeout(90_000)
  page.on('dialog', dialog => dialog.accept())
  await page.setViewportSize({width:1280,height:800})
  await registerAccount(page,request,'chat-owner')
  await page.goto('/friends')
  await page.getByRole('button',{name:'Create group'}).click()
  await page.getByLabel('Group name').fill('Chat circle')
  const created = page.waitForResponse(response => response.url().endsWith('/api/groups') && response.request().method()==='POST')
  await page.getByRole('dialog',{name:'Create group'}).getByRole('button',{name:'Create group',exact:true}).click()
  const {groupId} = await (await created).json()
  await expect(page.getByRole('log',{name:'Group conversation'})).toBeVisible()
  const invite = await page.getByLabel('Invite friends').inputValue()
  const memberContext = await browser.newContext({baseURL:test.info().project.use.baseURL!})
  const member = await memberContext.newPage()
  const token = invite.split('/').at(-1)!
  await registerAccount(member,request,'chat-member',token)
  await member.getByRole('button',{name:'Join group'}).click()
  await expect(member).toHaveURL(new RegExp(`group=${groupId}`))
  await page.getByLabel('Message').fill('Opening range looked clean')
  await page.getByRole('button',{name:'Send message'}).click()
  await expect(member.getByRole('log')).toContainText('Opening range looked clean',{timeout:12000})
  await member.getByLabel('Message').fill('My chart')
  await member.getByLabel('Add picture').setInputFiles({name:'chart.png',mimeType:'image/png',buffer:png})
  await member.getByRole('button',{name:'Send message'}).click()
  await expect(page.getByRole('img',{name:/Picture shared by/})).toBeVisible({timeout:12000})
  const source = await page.getByRole('img',{name:/Picture shared by/}).getAttribute('src')
  expect(source).toContain(`/api/groups/${groupId}/messages/`)
  expect((await page.request.get(source!)).status()).toBe(200)
  await page.screenshot({path:'test-results/group-chat-1280-dark.png',fullPage:true})
  await page.setViewportSize({width:1440,height:900})
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({path:'test-results/group-chat-1440-dark.png',fullPage:true})
  await page.reload()
  await expect(page.getByRole('complementary',{name:'Group members'})).toContainText('user_')
  await page.getByRole('button',{name:/Remove user_/}).click()
  expect((await member.request.get(`/api/groups/${groupId}/messages`)).status()).toBe(404)
  expect((await member.request.get(source!)).status()).toBe(404)
  await memberContext.close()
})
